/// 写 extension 文件（每次 spawn 前）：原子替换 + 目录不存在则建。
pub async fn ensure_extension(file: &std::path::Path) -> Result<()> {
    if let Some(dir) = file.parent() {
        tokio::fs::create_dir_all(dir).await?;
    }
    let tmp = file.with_extension("ts.tmp");
    tokio::fs::write(&tmp, HUB_EXTENSION_TS).await?;
    tokio::fs::rename(&tmp, file).await?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// extension 内容契约：工具注册 + loopback base + 无硬编码端口以外的地址
    #[test]
    fn extension_ts_contract() {
        assert!(HUB_EXTENSION_TS.contains("pi.registerTool"));
        for tool in [
            "hub_list_sessions",
            "hub_session_messages",
            "hub_get_settings",
            "hub_set_settings",
            // assistant-cron C1/C2：会话内定时工具面
            "hub_cron_create",
            "hub_cron_list",
            "hub_cron_delete",
        ] {
            assert!(
                HUB_EXTENSION_TS.contains(&format!("name: \"{tool}\"")),
                "缺工具 {tool}"
            );
        }
        assert!(HUB_EXTENSION_TS.contains("HUB_API_BASE"), "必须用 env base");
        assert!(
            HUB_EXTENSION_TS.contains("registerTool"),
            "必须走 registerTool 机制"
        );
        // cron 工具统一走 task-control 闸端点（不旁路 /api/tasks 写面）
        assert!(
            HUB_EXTENSION_TS.contains("action: \"create\"")
                && HUB_EXTENSION_TS.contains("action: \"delete\""),
            "cron 创建/删除必须走 task-control 闸端点"
        );
        // 红线注记：extension 不含会话删除/停止类调用（rm/stop 端点与 HTTP
        // DELETE 不进工具箱；任务删除走 task-control POST，非 REST DELETE）
        assert!(!HUB_EXTENSION_TS.contains("/rm"), "不得含删除端点");
        assert!(!HUB_EXTENSION_TS.contains("/stop"), "不得含停止端点");
        assert!(
            !HUB_EXTENSION_TS.contains("method: \"DELETE\""),
            "不得含 DELETE 调用"
        );
        // 注入/触发工具必写明委托语义
        assert!(
            HUB_EXTENSION_TS.contains("ONLY call on explicit user delegation"),
            "注入/触发工具必须写明委托语义"
        );
        // cron 创建工具必写明用户主动请求语义 + 权限门
        assert!(
            HUB_EXTENSION_TS.contains("ONLY call on explicit user request"),
            "cron 创建必须写明用户主动请求语义"
        );
        // 文档确认工作流入提示词
        assert!(
            ASSISTANT_SYSTEM_PROMPT.contains("document/confirmation triage"),
            "管家提示须含文档确认工作流"
        );
    }

    /// 管家提示契约：三职责 + 无破坏性授权
    #[test]
    fn system_prompt_contract() {
        assert!(ASSISTANT_SYSTEM_PROMPT.contains("session butler"));
        assert!(ASSISTANT_SYSTEM_PROMPT.contains("NEVER perform or propose destructive"));
        assert!(ASSISTANT_SYSTEM_PROMPT.contains("hub_list_sessions"));
    }

    /// 写盘：roundtrip + 幂等 + 原子无残留
    #[tokio::test]
    async fn ensure_extension_writes_atomic() {
        let dir = tempfile::tempdir().unwrap();
        let file = dir.path().join("sub/hub-assistant.ts");
        ensure_extension(&file).await.unwrap();
        let first = tokio::fs::read_to_string(&file).await.unwrap();
        assert!(first.contains("registerTool"));
        ensure_extension(&file).await.unwrap();
        let second = tokio::fs::read_to_string(&file).await.unwrap();
        assert_eq!(first, second);
        let residue: Vec<_> = std::fs::read_dir(file.parent().unwrap())
            .unwrap()
            .filter_map(|e| e.ok())
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .filter(|n| n.ends_with(".tmp"))
            .collect();
        assert!(residue.is_empty(), "不应残留临时文件: {residue:?}");
    }
}
